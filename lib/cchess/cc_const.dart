  static bool isInFort(int i) {
    return ccInFort[i] != 0;
  }

  static bool isInBoard(int i) {
    return ccInBoard[i] != 0;
  }

  static bool isHomeHalf(int i, int sd) {
    return (i & 0x80) != (sd << 7);
  }

  static bool isHomeAway(int i, int sd) {
    return !isHomeHalf(i, sd);
  }

  static int squareForward(int sq, int sd) {
    return sq - 16 + (sd << 5);
  }

  // 走法是否符合帅(将)的步长
  static bool isKingSpan(int sqSrc, int sqDst) {
    return ccLegalSpan[sqDst - sqSrc + 256] == 1;
  }

// 走法是否符合仕(士)的步长
  static bool isAdvisorSpan(int sqSrc, int sqDst) {
    return ccLegalSpan[sqDst - sqSrc + 256] == 2;
  }

// 走法是否符合相(象)的步长
  static bool isBishopSpan(int sqSrc, int sqDst) {
    return ccLegalSpan[sqDst - sqSrc + 256] == 3;
  }

// 相(象)眼的位置
  static int getBishopPin(int sqSrc, int sqDst) {
    return (sqSrc + sqDst) >> 1;
  }

// 马腿的位置
  static int getKnightPin(int sqSrc, int sqDst) {
    return sqSrc + ccKnightPin[sqDst - sqSrc + 256];
  }

// 是否在同一行
  static bool isSameRank(int sqSrc, int sqDst) {
    return ((sqSrc ^ sqDst) & 0xf0) == 0;
  }

// 是否在同一列
  static bool isSameFile(int sqSrc, int sqDst) {
    return ((sqSrc ^ sqDst) & 0x0f) == 0;
  }

  // 获得红黑标记(红子是8，黑子是16)
  static int getSideTag(int sd) {
    return 8 + (sd << 3);
  }

// 获得对方红黑标记
  static int getOppSideTag(int sd) {
    return 16 - (sd << 3);
  }
